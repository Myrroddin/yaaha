local perkBonusCache = {}

local function GetProcChances(recipeID)
	local operationInfo = C_TradeSkillUI.GetCraftingOperationInfo(
		recipeID, EMPTY_REAGENTS, nil, false)
	if not operationInfo then
		return 0, 0
	end
	local resourcefulnessChance, multicraftChance = 0, 0
	for _, statInfo in ipairs(operationInfo.bonusStats or {}) do
		if statInfo.bonusStatName == ITEM_MOD_RESOURCEFULNESS_SHORT then
			resourcefulnessChance = (statInfo.ratingPct or 0) / 100
		elseif statInfo.bonusStatName == ITEM_MOD_MULTICRAFT_SHORT then
			multicraftChance = (statInfo.ratingPct or 0) / 100
		end
	end
	return resourcefulnessChance, multicraftChance
end

local function GetSpecializationNodeRank(nodeID, configID)
	local nodeInfo = C_Traits.GetNodeInfo(configID, nodeID)
	if not nodeInfo then
		return 0
	elseif nodeInfo.maxRanks > 1 then
		-- Ranked profession nodes include an unlock entry. Only ranks beyond that
		-- entry contribute the node's per-rank proc modifier.
		local unlockEntryID = C_ProfSpecs.GetUnlockEntryForPath(nodeID)
		local unlockEntryInfo = unlockEntryID
			and C_Traits.GetEntryInfo(configID, unlockEntryID)
		return max((nodeInfo.currentRank or 0)
			- (unlockEntryInfo and unlockEntryInfo.maxRanks or 0), 0)
	end
	return C_ProfSpecs.GetStateForPerk(nodeID, configID)
		== Enum.ProfessionsSpecPerkState.Earned and 1 or 0
end

local function SumEarnedNodeBonuses(nodes, configID)
	local total = 0
	for nodeID, amount in pairs(nodes or {}) do
		total = total + amount * GetSpecializationNodeRank(nodeID, configID)
	end
	return total
end

local function GetPerkBonuses(recipeID)
	local groupID = recipeGroups[recipeID]
	if not groupID then
		return 0, 0
	end
	local skillLineID = C_TradeSkillUI.GetTradeSkillLineForRecipe(recipeID)
	local configID = skillLineID
		and C_ProfSpecs.GetConfigIDForSkillLine(skillLineID)
	if not configID or configID == 0 then
		return 0, 0
	end
	local configCache = perkBonusCache[configID]
	if not configCache then
		configCache = {}
		perkBonusCache[configID] = configCache
	end
	local cached = configCache[groupID]
	if cached then
		return cached.resourcefulness, cached.multicraft
	end
	local group = perkGroups[groupID]
	local resourcefulness = SumEarnedNodeBonuses(group.resourcefulness, configID)
	local multicraft = SumEarnedNodeBonuses(group.multicraft, configID)
	configCache[groupID] = {
		resourcefulness = resourcefulness,
		multicraft = multicraft,
	}
	return resourcefulness, multicraft
end

function module:ClearCache()
	wipe(perkBonusCache)
end

function module:GetExpectedRates(recipeID)
	local resourcefulnessChance, multicraftChance = GetProcChances(recipeID)
	if resourcefulnessChance == 0 and multicraftChance == 0 then
		return 0, 0, 0, 0
	end
	local resourcefulnessBonus, multicraftBonus = GetPerkBonuses(recipeID)
	local expectedRefund = resourcefulnessChance
		* BASE_RESOURCEFULNESS_REFUND * (1 + resourcefulnessBonus / 100)
	local expectedExtraYield = multicraftChance
		* BASE_MULTICRAFT_EXTRA_YIELD * (1 + multicraftBonus / 100)
	return resourcefulnessChance, multicraftChance,
		min(expectedRefund, 1), expectedExtraYield
end